#!/usr/bin/env bash
# Gardener's Walk — receding-horizon conformant planning copperbench wrapper.
#
#   bash run-walk.sh <config> <H> <F> <SHOTS> <seed>
#     <config> : alpha-mss (live session, grounder wake-up per shot)
#              | alpha-rebuilt (fresh solver + full re-ground per shot)
#              | clingo-rebuilt (fresh anchored window per shot, clingo's native 1{..}1 idiom)
#              | clingo-mss (window grounded ONCE with #external anchors over the grid)
#     <H>      : lookahead horizon        <F> : number of skittish frogs
#     <SHOTS>  : loop length (plan/execute/observe cycles)    <seed> : sample seed
#
# W is fixed at 30 (10% walls, connected free space, bump semantics). The seeded instance
# spec (gardener start, random frog starts, walls) is pre-generated by setup.sh from
# (F, seed) and shared verbatim by all four configs, so the comparison is 1:1 per sample.
# Frog movement during execution is each driver's own seeded RNG (own-sequence
# methodology, as in cutedge).
#
# A run that stops early (UNSAT: no safe h-step plan exists on that trajectory) emits
# RESULT_SURVIVED but NO RESULT_SECONDS, so the cell counts as unfinished; full survivals
# report the summed per-shot solve time (excluding JVM startup), the paper's measure.
set -u
source "$(cd "$(dirname "$0")" && pwd)/_common.sh"

CONFIG="${1:?config token required}"
H="${2:?horizon required}"
F="${3:?frog count required}"
SHOTS="${4:?shot count required}"
SEED="${5:?sample seed required}"
announce walk "$H-$F-$SHOTS-s$SEED"

W=30
SPEC="$EXAMPLES/walk/instances/inst-W${W}-f${F}-s${SEED}.spec"
[[ -f "$SPEC" ]] || { echo "missing instance spec $SPEC (run setup.sh)" >&2; exit 1; }

# emit_from_result <logfile> — parse the drivers' RESULT line; only full survivals score.
emit_from_result() {
    local surv total
    surv="$(grep -oE 'survived=[0-9]+/[0-9]+' "$1" | tail -1)"
    total="$(grep -oE 'totalSolve=[0-9.]+' "$1" | tail -1 | cut -d= -f2)"
    echo "RESULT_SURVIVED=${surv#survived=}"
    if [[ "${surv#survived=}" == "$SHOTS/$SHOTS" && -n "$total" ]]; then
        emit "$total"
    fi
}

case "$CONFIG" in
  alpha-mss|alpha-rebuilt)
    mode="live"; [[ "$CONFIG" == alpha-rebuilt ]] && mode="batch"
    # per-shot cap just under the runsolver wall cap so the wall cap is the effective limit
    JVM_EXTRA="-Dwalk.shotCapSec=1700" run_java GardenersWalkBenchmark "$mode" "$W" "$H" "$F" "$SHOTS" "$SEED" "$SPEC"
    emit_from_result "$JAVA_LOG"
    ;;

  clingo-rebuilt|clingo-mss)
    mode="batch"; [[ "$CONFIG" == clingo-mss ]] && mode="mss"
    CLOG="$(mktemp)"; trap 'rm -f "$CLOG"' EXIT
    "$PYTHON" "$EXAMPLES/walk/walk_clingo.py" "$mode" "$W" "$H" "$F" "$SHOTS" "$SEED" "$SPEC" 2>&1 | tee "$CLOG"
    emit_from_result "$CLOG"
    ;;

  *) echo "unknown config: $CONFIG" >&2; exit 2 ;;
esac
